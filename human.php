                done++; updateBar(); next();
            };
            xhr.send(JSON.stringify({ name: file.name, data: b64, csrf: FM_CSRF }));
        };
        reader.onerror = function () {
            logLine('✘ ' + file.name + ' — FileReader error', true);
            done++; updateBar(); next();
        };
        reader.readAsDataURL(file);
    }

    input.addEventListener('change', function () {
        enqueue(input.files);
        input.value = '';
    });

    drop.addEventListener('click', function () { input.click(); });

    ['dragenter', 'dragover'].forEach(function (ev) {
        drop.addEventListener(ev, function (e) { e.preventDefault(); drop.classList.add('hover'); });
    });
    ['dragleave', 'drop'].forEach(function (ev) {
        drop.addEventListener(ev, function (e) { e.preventDefault(); drop.classList.remove('hover'); });
    });
    drop.addEventListener('drop', function (e) {
        if (e.dataTransfer && e.dataTransfer.files) enqueue(e.dataTransfer.files);
    });

    // Prevent browser from navigating when dropping elsewhere
    window.addEventListener('dragover', function (e) { e.preventDefault(); });
    window.addEventListener('drop',     function (e) { e.preventDefault(); });
})();
